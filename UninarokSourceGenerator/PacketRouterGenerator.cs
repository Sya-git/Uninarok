            //    sb.AppendLine($"            {eventName}?.Invoke(in pack);");
            //    sb.AppendLine($"        }}");
            //    sb.AppendLine();
            //}

            sb.AppendLine("        public static void RoutePacket(ushort id, ReadOnlySpan<byte> packetData)");
            sb.AppendLine("        {");
            sb.AppendLine("            switch (id)");
            sb.AppendLine("            {");
            foreach(var (id, _, typeName) in inPacketInfos)
            {
                string hexFormatId = $"0x{id:X4}";
                string safeName = typeName.Replace(".", "_");
                string shortTypeName = typeName.Substring(typeName.LastIndexOf('.') + 1);
                sb.AppendLine($"                case {hexFormatId}:");
                sb.AppendLine($"                {{");
                sb.AppendLine($"                    {typeName} pack = new(packetData);");
                sb.AppendLine($"                    UninarokPackageDispatcher.Dispatch<{typeName}>(in pack);");
