        public void Initialize(GeneratorInitializationContext context)
        {
            context.RegisterForSyntaxNotifications(() => new PacketSyntaxReceiver());
        }

        public void Execute(GeneratorExecutionContext context)
        {
            if (!(context.SyntaxReceiver is PacketSyntaxReceiver receiver))
                return;

            var inPacketInfos = new List<(ushort Id, short Size, string TypeName)>();
            var outPacketInfos = new List<(ushort Id, short Size, string TypeName)>();

            // 1. Coleta os pacotes com [InPacket]
            foreach (var structDecl in receiver.CandidateStructs)
            {
                var model = context.Compilation.GetSemanticModel(structDecl.SyntaxTree);
                var symbol = model.GetDeclaredSymbol(structDecl);

                if (symbol == null) continue;

                foreach (var attr in symbol.GetAttributes())
                {
                    if (attr.AttributeClass?.Name == "InPacketAttribute" && attr.ConstructorArguments.Length >= 2)
                    {
                        // O construtor recebe o Enum (convertido para ushort) e o short size
                        ushort id = (ushort)attr.ConstructorArguments[0].Value;
                        short size = (short)attr.ConstructorArguments[1].Value;
                        string typeName = symbol.ToDisplayString();

                        inPacketInfos.Add((id, size, typeName));
                    }
                }
            }

            foreach (var structDecl in receiver.CandidateStructs)
            {
                var model = context.Compilation.GetSemanticModel(structDecl.SyntaxTree);
                var symbol = model.GetDeclaredSymbol(structDecl);

                if (symbol == null) continue;

                foreach (var attr in symbol.GetAttributes())
                {
                    if (attr.AttributeClass?.Name == "OutPacketAttribute" && attr.ConstructorArguments.Length >= 2)
                    {
                        // O construtor recebe o Enum (convertido para ushort) e o short size
                        ushort id = (ushort)attr.ConstructorArguments[0].Value;
                        short size = (short)attr.ConstructorArguments[1].Value;
                        string typeName = symbol.ToDisplayString();

                        outPacketInfos.Add((id, size, typeName));
                    }
                }
            }

            if (inPacketInfos.Count == 0) return;

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Buffers;");
            sb.AppendLine("");
            sb.AppendLine("namespace Uninarok.Networking {");
            sb.AppendLine("    public static partial class UninarokNetworkingRouter");
            sb.AppendLine("    {");


            // 2. Gera a Tabela de Tamanhos estática (Lookup Direto de 65536 posições - O(1) puro)
            sb.AppendLine("        /// <summary>");
            sb.AppendLine("        /// Tabela de tamanho de pacotes indexada por ushort (-2 indica pacote desconhecido)");
            sb.AppendLine("        /// </summary>");
            sb.AppendLine("        private static readonly short[] PacketSizes = InitializePacketSizes();");
            sb.AppendLine();
            sb.AppendLine("        private static short[] InitializePacketSizes()");
            sb.AppendLine("        {");
            sb.AppendLine("            short[] sizes = new short[65536];"); // Nota: ajustado para 65536 fechado
            sb.AppendLine("            Array.Fill(sizes, (short)-2);");

            foreach (var (id, size, _) in inPacketInfos)
            {
                var hexId = $"0x{id:X4}";
                sb.AppendLine($"            sizes[{hexId}] = {size};");
            }

            foreach (var (id, size, _) in outPacketInfos)
            {
                var hexId = $"0x{id:X4}";
                sb.AppendLine($"            sizes[{hexId}] = {size};");
            }

            sb.AppendLine("            return sizes;");
            sb.AppendLine("        }");
            sb.AppendLine();

            sb.AppendLine($"       public static short GetLength(ushort id)");
            sb.AppendLine("        {");
            sb.AppendLine("            return PacketSizes[id];");
            sb.AppendLine("        }");

            // 3. Gera os Delegates, Eventos e Métodos de Dispatch para cada pacote
            //foreach (var (_, _, typeName) in packetInfos)
