using System.IO;
using NUnit.Framework;
using Uninarok.Networking.Editor;

namespace Uninarok.Networking.Tests
{
    // SPEC-0001 FR-18, FR-19; plan 4.8: the generator validates the fixture before it writes anything.
    public class HerculesPacketTableGeneratorTests
    {
        static string Json(string entries) => "{\n\"_source\": \"test\",\n\"lengths\": {\n" + entries + "\n}\n}";

        [Test]
        public void Generate_EmitsAnIdentifiedAutoGeneratedTable()
        {
            string src = HerculesPacketTableGenerator.Generate(Json("\"0x0064\": 55,\n\"0x006B\": -1"));
            StringAssert.Contains("<auto-generated>", src);
            StringAssert.Contains("class HerculesPacketTable : IPacketLengthTable", src);
            StringAssert.Contains("0x0064", src);
            StringAssert.Contains("0x006B", src);
            StringAssert.Contains("PacketCount = 2", src);
            StringAssert.Contains("Source: test", src);
        }

        [Test]
        public void Generate_SortsIdsAscending()
        {
            string src = HerculesPacketTableGenerator.Generate(Json("\"0x0200\": 5,\n\"0x0010\": 6"));
            Assert.Less(src.IndexOf("0x0010,"), src.IndexOf("0x0200,"));
        }

        [TestCase(0)]
        [TestCase(1)]
        [TestCase(-2)]
        [TestCase(-5)]
        [TestCase(40000)]
        public void Generate_RejectsInvalidLength(int value)
        {
            var e = Assert.Throws<InvalidDataException>(() =>
                HerculesPacketTableGenerator.Generate(Json("\"0x0042\": " + value)));
            StringAssert.Contains("0x0042", e.Message);
        }

        [Test]
        public void Generate_RejectsDuplicateIds()
        {
            var e = Assert.Throws<InvalidDataException>(() =>
                HerculesPacketTableGenerator.Generate(Json("\"0x0042\": 5,\n\"0x0042\": 6")));
            StringAssert.Contains("Duplicate", e.Message);
        }

        [Test]
        public void Generate_RejectsIdZero()
        {
            Assert.Throws<InvalidDataException>(() => HerculesPacketTableGenerator.Generate(Json("\"0x0000\": 5")));
        }

        [Test]
        public void Generate_RejectsAnEmptyFixture()
        {
            Assert.Throws<InvalidDataException>(() => HerculesPacketTableGenerator.Generate(Json("")));
        }
    }
}
